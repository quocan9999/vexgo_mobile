"""Regenerate the render-only adapter for legacy client labels from ARB."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
messages = json.loads((root / 'lib/l10n/app_vi.arb').read_text(encoding='utf-8'))
lines = ["// Generated by tool/generate_client_labels.py; edit ARB instead.",
    "import 'package:flutter/widgets.dart';", "import 'locale_controller.dart';", "",
    "/// Use only for client labels/errors at render boundaries, never user chat or policy content.",
    "String localizedClientLabel(BuildContext context, String value) => switch (value) {"]
seen = set()
for key, value in messages.items():
    if key.startswith('@') or not isinstance(value, str) or '{p' in value or value in seen:
        continue
    seen.add(value)
    lines.append('  ' + json.dumps(value, ensure_ascii=False) + ' => context.l10n.' + key + ',')
lines.extend(['  _ => value,', '};', '',
    'String? localizedClientValidation(BuildContext context, String? value) =>',
    '    value == null ? null : localizedClientLabel(context, value);', ''])
(root / 'lib/core/localization/client_labels.dart').write_text('\n'.join(lines), encoding='utf-8')
